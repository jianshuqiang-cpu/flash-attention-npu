import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

# Forward: six lightweight FP16/BF16 routers refer to 48 separately compiled
# leaf launchers (dtype x layout x path x softcap). Each leaf contains only four
# device entries: LSE x cache mode. The three FP8 TUs remain independent.
# head_dim and sequence lengths are runtime axes and are not generated.
#
# Backward: six lightweight FP16/BF16 routers refer to 48 separately compiled
# leaf launchers (dtype x layout x mask x deterministic x softcap); each leaf
# holds exactly one FlashAttentionV3Bwd950 instantiation, mirroring the forward
# split so the bwd kernel templates compile in parallel across cores.
DTYPE_MAP = {"fp16": "half", "bf16": "bfloat16_t", "fp8": "float8_e4m3_t"}
LAYOUTS = [
    ("bsnd", "BSND", "Format::BSND"),
    ("tnd", "TND", "Format::TND"),
    ("bnsd", "BNSD", "Format::BNSD"),
]
# Forward paths: (key, mask category token, use-DN fast path).
PATHS = [
    ("nomask", "MaskCategory::NO_MASK", False),
    ("dn", "MaskCategory::NO_MASK", True),
    ("causal", "MaskCategory::MASK_CAUSAL", False),
    ("swa", "MaskCategory::MASK_SWA", False),
]
# Backward layout tokens are the BwdInputLayout enum constants (bwd_dispatch.hpp),
# mirrored from FAGTiling950::Layout (BSND = 0, TND = 1, BNSD = 2).
BWD_LAYOUTS = [
    ("bsnd", "BSND"),
    ("tnd", "TND"),
    ("bnsd", "BNSD"),
]
BWD_MASKS = [("nomask", False), ("mask", True)]
BWD_DTMS = [("ndtm", False), ("dtm", True)]
PRELUDE = """/**
 * Copyright (c) 2026 Huawei Technologies Co., Ltd.
 * Modified by Minghua Shen, 2026.
 */
// Generated by generate_kernels.py; do not edit.
"""


@dataclass
class Kernel:
    dtype: str
    layout: str
    filename: str
    content: str


def fwd_kernel(dtype_key: str, layout: tuple) -> Kernel:
    ctype = DTYPE_MAP[dtype_key]
    layout_key, display, fmt = layout
    header = "fwd_dispatch_quant_impl.hpp" if dtype_key == "fp8" else "fwd_dispatch_impl.hpp"
    content = (
        PRELUDE + f"// v3 (950) {dtype_key} x {display} forward entry.\n"
        + f'#include "../{header}"\n\n'
        + f"template void launch_fwd_impl<{ctype}, {fmt}>(const FwdLaunchArgs& a);\n"
    )
    return Kernel(dtype_key, layout_key, f"fwd_dispatch_{dtype_key}_{layout_key}.cpp", content)


def fwd_variants():
    for dtype in ("fp16", "bf16"):
        for layout_key, _, fmt in LAYOUTS:
            for path, mask, dn in PATHS:
                for softcap in (False, True):
                    args = f"{DTYPE_MAP[dtype]}, {fmt}, {mask}, {str(dn).lower()}, {str(softcap).lower()}"
                    yield dtype, layout_key, path, softcap, args


def bwd_kernel(dtype_key: str, layout: tuple) -> Kernel:
    ctype = DTYPE_MAP[dtype_key]
    layout_key, layout_token = layout
    content = (
        PRELUDE + f"// v3 (950) {dtype_key} x {layout_token} backward entry.\n"
        + '#include "../bwd_dispatch_impl.hpp"\n\n'
        + f"template void bwd_dispatch_run<{ctype}, {layout_token}>(const BwdLaunchArgs& a);\n"
    )
    return Kernel(dtype_key, layout_key, f"bwd_dispatch_{dtype_key}_{layout_key}.cpp", content)


def bwd_variants():
    for dtype in ("fp16", "bf16"):
        for layout_key, layout_token in BWD_LAYOUTS:
            for mask_key, mask in BWD_MASKS:
                for dtm_key, dtm in BWD_DTMS:
                    for softcap in (False, True):
                        args = f"{DTYPE_MAP[dtype]}, {layout_token}, {str(mask).lower()}, " \
                               f"{str(dtm).lower()}, {str(softcap).lower()}"
                        yield dtype, layout_key, mask_key, dtm_key, softcap, args


def get_all_kernels() -> List[Kernel]:
    kernels = [fwd_kernel(dtype, layout) for dtype in DTYPE_MAP for layout in LAYOUTS]
    for dtype, layout, path, softcap, args in fwd_variants():
        kernels.append(Kernel(
            dtype, layout, f"fwd_variant_{dtype}_{layout}_{path}_sc{int(softcap)}.cpp",
            PRELUDE + f"// {path}, softcap={softcap}: four LSE/cache combinations.\n"
            + '#include "../fwd_dispatch_variant_impl.hpp"\n\n'
            + f"template void launch_fwd_variant<{args}>(const FwdLaunchArgs& a);\n"))
    kernels.extend(bwd_kernel(dtype, layout) for dtype in ("fp16", "bf16") for layout in BWD_LAYOUTS)
    for dtype, layout, mask_key, dtm_key, softcap, args in bwd_variants():
        kernels.append(Kernel(
            dtype, layout, f"bwd_variant_{dtype}_{layout}_{mask_key}_{dtm_key}_sc{int(softcap)}.cpp",
            PRELUDE + f"// {mask_key}, deterministic={dtm_key == 'dtm'}, softcap={softcap}: one kernel.\n"
            + '#include "../bwd_dispatch_variant_impl.hpp"\n\n'
            + f"template void bwd_dispatch_variant<{args}>(const BwdLaunchArgs& a);\n"))
    return kernels


def variant_declarations():
    return (
        PRELUDE + "#ifndef FA950_FWD_DISPATCH_VARIANTS_HPP\n#define FA950_FWD_DISPATCH_VARIANTS_HPP\n\n"
        + '#include "../fwd_dispatch.hpp"\n\n'
        + "template <typename DType, Format kLayout, MaskCategory kMask, bool kDn, bool kSoftcap>\n"
        + "void launch_fwd_variant(const FwdLaunchArgs& a);\n\n"
        + "\n".join(f"extern template void launch_fwd_variant<{args}>(const FwdLaunchArgs& a);"
                    for _, _, _, _, args in fwd_variants())
        + "\n\n#endif\n"
    )


def bwd_variant_declarations():
    return (
        PRELUDE + "#ifndef FA950_BWD_DISPATCH_VARIANTS_HPP\n#define FA950_BWD_DISPATCH_VARIANTS_HPP\n\n"
        + '#include "../bwd_dispatch.hpp"\n\n'
        + "template <typename DType, uint32_t kInputLayout, bool kMask, bool kDtm, bool kSoftcap>\n"
        + "void bwd_dispatch_variant(const BwdLaunchArgs& a);\n\n"
        + "\n".join(f"extern template void bwd_dispatch_variant<{args}>(const BwdLaunchArgs& a);"
                    for _, _, _, _, _, args in bwd_variants())
        + "\n\n#endif\n"
    )


def main(output_dir: Optional[str]) -> None:
    output = Path(output_dir) if output_dir is not None else Path(__file__).parent
    output.mkdir(parents=True, exist_ok=True)
    kernels = get_all_kernels()
    files = {kernel.filename: kernel.content for kernel in kernels}
    files["fwd_dispatch_variants.hpp"] = variant_declarations()
    files["bwd_dispatch_variants.hpp"] = bwd_variant_declarations()
    changed = 0
    for name, content in files.items():
        path = output / name
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            changed += 1
    # Remove only obsolete leaves owned by this generator, never handwritten TUs.
    for glob_pattern in ("fwd_variant_*.cpp", "bwd_variant_*.cpp"):
        for path in output.glob(glob_pattern):
            if path.name not in files and "// Generated by generate_kernels.py; do not edit." in path.read_text():
                path.unlink()
    print(f"Generated {len(kernels)} dispatch TUs in {output} ({changed} files updated)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate 950/v3 routers and per-path/softcap kernel TUs.")
    parser.add_argument("-o", "--output_dir", help="Defaults to this script's directory.")
    main(parser.parse_args().output_dir)
